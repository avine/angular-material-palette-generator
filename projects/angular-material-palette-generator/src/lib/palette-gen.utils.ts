import { buildPalette } from './palette-gen-engine/palette-gen-engine';
import { PaletteGenFormValue } from './palette-gen-form/palette-gen-form.types';
import { getPaletteTones } from './palette-gen.config';
import { PaletteGenData, PaletteGenDataListItem } from './palette-gen.types';
import { PaletteMode, PaletteName } from './palette-matching/palette-matching.types';
import { PALETTE_NAMES } from './palette-matching/palette-matching.utils';

const normalizeHexColor = (color: string) => (color.startsWith('#') ? color : `#${color}`);

export const buildPaletteGenData = (formValue: PaletteGenFormValue | undefined): PaletteGenData => {
  if (!formValue) {
    return { list: [], colorMap: {}, issues: [] };
  }
  const { anchors, neutral } = formValue;

  const { tones, issues } = buildPalette(
    anchors.map(({ color, tone }) => ({ color: normalizeHexColor(color), tone: tone ?? undefined })),
    getPaletteTones(neutral),
  );

  const list = tones.map(({ tone, color, anchored }) => ({ percentage: tone, color, anchored }));

  const colorMap = list.reduce(
    (map, { percentage, color }) => {
      map[percentage] = color;
      return map;
    },
    {} as Record<number, string>,
  );

  return { list, colorMap, issues };
};

export const buildSassMapStringified = (
  formValue: PaletteGenFormValue,
  dataList: PaletteGenDataListItem[],
  indent = '  ',
) => {
  const settings = `${indent}// ${JSON.stringify(formValue)}\n`;

  const sassMap = dataList.map(({ percentage, color }) => `${indent}${percentage}: ${color},\n`).join('');

  return settings + sassMap;
};

/**
 * Build a Sass file with the same structure as the file generated by `ng generate @angular/material:theme-color`.
 * The settings of each palette are kept in a comment, so that the file can be imported back.
 */
export const buildSassFileStringified = (
  formValueMap: Record<PaletteName, PaletteGenFormValue>,
  colorScheme: PaletteMode,
) => {
  const palettes = PALETTE_NAMES.map((paletteName) => {
    const formValue = formValueMap[paletteName];
    const sassMap = buildSassMapStringified(formValue, buildPaletteGenData(formValue).list, '    ');
    return `  ${paletteName}: (\n${sassMap}  ),\n`;
  }).join('');

  return `// This file was generated by Angular Material Palette Generator.
// https://avine.github.io/angular-material-palette-generator
// Color scheme: ${colorScheme}

@use 'sass:map';

$_palettes: (
${palettes});

$_rest: (
  secondary: map.get($_palettes, secondary),
  neutral: map.get($_palettes, neutral),
  neutral-variant: map.get($_palettes, neutral-variant),
  error: map.get($_palettes, error),
);

$primary-palette: map.merge(map.get($_palettes, primary), $_rest);
$tertiary-palette: map.merge(map.get($_palettes, tertiary), $_rest);
`;
};
