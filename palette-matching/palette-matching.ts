import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';

// Generates the following file from the `@angular/material` version installed in the root project:
//    `projects/angular-material-palette-generator/src/lib/palette-matching/palette-matching.config.ts`
//
// Usage:
//    `npm run palette-matching`            -> updates the file
//    `npm run palette-matching -- --check` -> only checks that the file is up to date (exit code 1 otherwise)
import {
  PALETTE_MATCHING_ERRORS,
  PALETTE_PERCENTAGE_MATCHING_MAP,
  PALETTE_TOKEN_MATCHING_MAP,
} from './palette-matching.utils.ts';

// Path relative to the root of the workspace
const CONFIG_DISPLAY_PATH =
  'projects/angular-material-palette-generator/src/lib/palette-matching/palette-matching.config.ts';
const CONFIG_PATH = resolve(import.meta.dirname, '..', CONFIG_DISPLAY_PATH);

const isCheck = process.argv.includes('--check');

if (PALETTE_MATCHING_ERRORS.length) {
  console.error('✖ Palette matching errors:\n');
  console.error(PALETTE_MATCHING_ERRORS.join('\n'));
  process.exit(1);
}

// Note: objects are indented, otherwise Prettier would collapse them on a single line when they fit.
const serialize = (map: Record<string, unknown>) => JSON.stringify(map, null, 2);

const source = `// -----------------------------------------------------------------------------------------------
// AUTO-GENERATED FILE - DO NOT EDIT
//
// Generated by \`palette-matching/palette-matching.ts\`.
// To update it, run: \`npm run palette-matching\`
// -----------------------------------------------------------------------------------------------

import { PalettePercentageMatchingMap, PaletteTokenMatchingMap } from './palette-matching.types';

export const PALETTE_TOKEN_MATCHING_MAP: PaletteTokenMatchingMap = ${serialize(PALETTE_TOKEN_MATCHING_MAP)};

export const PALETTE_PERCENTAGE_MATCHING_MAP: PalettePercentageMatchingMap = ${serialize(PALETTE_PERCENTAGE_MATCHING_MAP)};
`;

const prettierConfig = await resolveConfig(CONFIG_PATH);
const content = await format(source, { ...prettierConfig, filepath: CONFIG_PATH });
const current = await readFile(CONFIG_PATH, 'utf8').catch(() => undefined);

if (content === current) {
  console.log(`✔ "${CONFIG_DISPLAY_PATH}" is up to date`);
} else if (isCheck) {
  console.error(`✖ "${CONFIG_DISPLAY_PATH}" is outdated, run: npm run palette-matching`);
  process.exit(1);
} else {
  await writeFile(CONFIG_PATH, content);
  console.log(`✔ "${CONFIG_DISPLAY_PATH}" updated`);
}
